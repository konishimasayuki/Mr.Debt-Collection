// 郵便番号。入力の受け取りと、入っていないときの住所からの逆引き
import { client, call, check, done, reset } from './h.js';
import { 郵便番号を整える, 住所から郵便番号 } from '../api/_zip.js';

(async () => {
  await client.connect();
  await reset();
  await call('setup', { method: 'POST', body: {} });
  const 見る = async (id) => (await call('customer', { q: { id } })).body.顧客;

  console.log('■ 打ち方がばらついても 123-4567 にそろえる');
  for (const [入, 期待] of [
    ['1234567', '123-4567'],
    ['123-4567', '123-4567'],
    ['〒123-4567', '123-4567'],
    ['１２３４５６７', '123-4567'],          // 全角
    ['〒 123 - 4567', '123-4567'],
    ['123', null],                           // 足りない
    ['12345678', null],                      // 多い
    ['', null],
    [null, null],
  ]) {
    check(`${JSON.stringify(入)} → ${期待}`, 郵便番号を整える(入) === 期待,
      郵便番号を整える(入));
  }

  console.log('■ 住所から郵便番号を引ける（町域まで当たる）');
  for (const [住, 期待] of [
    ['東京都千代田区千代田1-1', '100-0001'],
    ['千代田区永田町1-7-1', '100-0014'],                  // 都道府県が無くても
    ['大阪市北区梅田3丁目1-1', '530-0001'],
    ['北海道札幌市中央区旭ヶ丘2-1', '064-0941'],          // ヶとケの違いを越える
    ['北海道札幌市中央区旭ケ丘2-1', '064-0941'],
    ['愛知県名古屋市中村区名駅1-1-4', '450-0002'],        // 「その他」がその町の代表
    ['福岡県久留米市東町1-1', '830-0032'],
    ['沖縄県那覇市おもろまち1-1-1', '900-0006'],
  ]) {
    const r = await 住所から郵便番号(住);
    check(`${住} → ${期待}`, r && r.番号 === 期待 && r.どこまで === '町域',
      r);
  }

  console.log('■ 町域まで決まらないときは、市区町村の番号にする');
  // 京都の通り名の住所は町名では当たらない。「以下に掲載がない場合」の番号になる
  const 京 = await 住所から郵便番号('京都府京都市中京区烏丸通');
  check('市区町村までで返す', 京 && 京.どこまで === '市区町村', 京);
  // 丁目で番号が分かれる町（代表が無い）は、黙って片方を出さない
  const 札 = await 住所から郵便番号('北海道札幌市中央区大通西5丁目1');
  check('丁目で分かれる町は市区町村までにとどめる',
    札 && 札.どこまで === '市区町村', 札);

  console.log('■ 引けないものは引けないと言う');
  for (const 住 of ['', null, 'どこでもない町9-9-9', 'あああ']) {
    check(`${JSON.stringify(住)} → なし`, (await 住所から郵便番号(住)) === null,
      await 住所から郵便番号(住));
  }

  console.log('■ 住所の文に〒が混ざっていたら、それを採る');
  const 混 = await 住所から郵便番号('〒150-0002 東京都渋谷区渋谷1-1');
  check('住所に書いてある番号を使う',
    混 && 混.番号 === '150-0002' && 混.どこまで === '住所に書いてある', 混);

  console.log('■ 新規登録のときに一緒に入れられる');
  const r = await call('customers', { method: 'POST', body: {
    名前: 'ユウビン 太郎', よみ: 'ユウビン タロウ',
    郵便番号: '8300032', 住所: '福岡県久留米市東町1-1',
    月々の金額: 30000, 回数: 24, 支払日: 27, 開始月: '2026-09' } });
  check('登録できる', r.code === 200, r.body);
  const id = r.body.id;
  let c = await 見る(id);
  check('ハイフンを足してしまってある', c.郵便番号 === '830-0032', c.郵便番号);
  check('入っているので推定は出さない', c.郵便番号推定 === '', c.郵便番号推定);

  console.log('■ 7桁にならない郵便番号は断る');
  const 駄 = await call('customers', { method: 'POST', body: {
    名前: 'ダメ 番号', 郵便番号: '12345',
    月々の金額: 10000, 回数: 12, 支払日: 1, 開始月: '2026-09' } });
  check('断る', 駄.code === 400, 駄.code);
  check('理由を言う', /7桁/.test(駄.body.error || ''), 駄.body);

  console.log('■ 顧客編集から直せる');
  const u = await call('customer', { method: 'PATCH', body: {
    id, 郵便番号: '〒１００−０００１', 住所: '東京都千代田区千代田1-1' } });
  check('直せる', u.code === 200, u.body);
  c = await 見る(id);
  check('全角でも〒付きでも入る', c.郵便番号 === '100-0001', c.郵便番号);

  const 駄2 = await call('customer', { method: 'PATCH', body: { id, 郵便番号: 'abc' } });
  check('数字にならないものは断る', 駄2.code === 400, 駄2.code);
  c = await 見る(id);
  check('断ったので前のまま', c.郵便番号 === '100-0001', c.郵便番号);

  console.log('■ 空にすると、住所から逆に引いた番号が出る');
  await call('customer', { method: 'PATCH', body: { id, 郵便番号: '' } });
  c = await 見る(id);
  check('入力は空になる', c.郵便番号 === '', c.郵便番号);
  check('推定が出る', c.郵便番号推定 === '100-0001', c.郵便番号推定);
  check('どこまで当たったかも返す', c.郵便番号推定のもと === '町域', c.郵便番号推定のもと);

  console.log('■ 住所を変えれば、推定も付いてくる');
  await call('customer', { method: 'PATCH', body: {
    id, 住所: '沖縄県那覇市おもろまち1-1-1' } });
  c = await 見る(id);
  check('新しい住所の番号になる', c.郵便番号推定 === '900-0006', c.郵便番号推定);

  console.log('■ 住所が無ければ、推定も出さない');
  await call('customer', { method: 'PATCH', body: { id, 住所: '' } });
  c = await 見る(id);
  check('住所が空', c.住所 === '', c.住所);
  check('推定も空', c.郵便番号推定 === '', c.郵便番号推定);

  console.log('■ 入れてもらった番号は、住所より強い');
  // 住所の打ち間違いで番号が変わってしまわないこと。
  // 入っているときは逆引きの表を**開きもしない**
  await call('customer', { method: 'PATCH', body: {
    id, 郵便番号: '999-9999', 住所: '東京都千代田区千代田1-1' } });
  c = await 見る(id);
  check('入力がそのまま出る', c.郵便番号 === '999-9999', c.郵便番号);
  check('推定は出さない', c.郵便番号推定 === '', c.郵便番号推定);

  await done();
})();
