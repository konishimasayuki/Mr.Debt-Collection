// ダッシュボード：月ごとの予定回収額（％と入れ替えた表示）
import { client, call, check, done, reset } from './h.js';

const 前月 = (n) => {
  const d = new Date();
  d.setUTCDate(1);
  d.setUTCMonth(d.getUTCMonth() - n);
  return `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}`;
};

(async () => {
  await client.connect();
  await reset();
  await call('setup', { method: 'POST', body: {} });
  const 作る = async (o) => (await call('customers', { method: 'POST', body: o })).body;
  const 払う = (id, 日, 額) => call('payments', { method: 'POST', body: {
    顧客id: id, 日付: 日, 金額: 額, メモ: '現金で受け取った' } });
  const 見る = async () => (await call('dashboard')).body;
  const 月を引く = (d, ym) => d.月.find((m) => m.年月 === ym);

  // 期日が過ぎている月を作る。2か月前から毎月20日に 30,000円 × 2名
  const 開始 = 前月(2);
  const A = await 作る({ 名前: 'ダッシュ 一郎', よみ: 'ダッシュ イチロウ',
    月々の金額: 30000, 回数: 6, 支払日: 20, 開始月: 開始 });
  const B = await 作る({ 名前: 'ダッシュ 二郎', よみ: 'ダッシュ ジロウ',
    月々の金額: 50000, 回数: 6, 支払日: 20, 開始月: 開始 });

  console.log('■ 率は返さなくなり、予定回収額を返す');
  let d = await 見る();
  const m0 = 月を引く(d, 開始);
  check('その月がある', !!m0, d.月.map((m) => m.年月));
  check('率は返さない', m0.率 === undefined, m0.率);
  check('予定回収額を返す', typeof m0.予定回収額 === 'number', m0.予定回収額);
  check('予定回収額は80,000円', m0.予定回収額 === 80000, m0.予定回収額);
  check('未回収額も80,000円', m0.未回収額 === 80000, m0.未回収額);
  check('全件は2件', m0.全件 === 2, m0.全件);

  console.log('■ 払い終えた回も、予定回収額には足す');
  // 一郎の1回目（30,000円）を払う
  await 払う(A.id, `${開始}-20`, 30000);
  d = await 見る();
  const m1 = 月を引く(d, 開始);
  check('予定回収額は80,000円のまま', m1.予定回収額 === 80000, m1.予定回収額);
  check('未回収額は50,000円に減る', m1.未回収額 === 50000, m1.未回収額);
  check('回収済みは1件', m1.回収済み === 1, m1.回収済み);
  check('全件は2件のまま', m1.全件 === 2, m1.全件);

  console.log('■ ボーナスの回も予定回収額に入る');
  await call('customer', { method: 'PATCH', body: {
    id: B.id, ボーナス月: [Number(開始.slice(5, 7))], ボーナス日: 20,
    ボーナス金額: 100000 } });
  d = await 見る();
  const m2 = 月を引く(d, 開始);
  check('予定回収額は180,000円', m2.予定回収額 === 180000, m2.予定回収額);
  check('全件は3件', m2.全件 === 3, m2.全件);

  console.log('■ 月ごとに分かれている');
  const 翌 = 前月(1);
  const m3 = 月を引く(d, 翌);
  check('翌月もある', !!m3, d.月.map((m) => m.年月));
  check('翌月の予定回収額は80,000円', m3 && m3.予定回収額 === 80000, m3 && m3.予定回収額);

  // ── 今月ぶん ──────────────────────────────
  //
  // ここが抜けていて不具合を出した。9月17日に見ると、支払日27日の回は
  // まだ期日が来ていないので落ち、「9月分 30,000円」と出ていた。
  // 予定回収額は**その月まるごと**でなければならない。
  console.log('■ 今月は、まだ期日の来ていない回も予定回収額に入れる');
  await reset();
  await call('setup', { method: 'POST', body: {} });
  const 今月 = 前月(0);
  const 末日 = new Date(Date.UTC(Number(今月.slice(0, 4)), Number(今月.slice(5, 7)), 0))
    .getUTCDate();
  const 今日 = Number((await 見る()).本日.slice(8, 10));

  // 今日より前の支払日と、今日より後の支払日を作る。
  // 月末が近い日に走らせても成り立つよう、今日を挟んで取る
  const 早い日 = Math.max(1, 今日 - 1);
  const 遅い日 = Math.min(末日, 今日 + 1);
  if (早い日 < 遅い日) {
    const 開始2 = 前月(1);
    const E = await 作る({ 名前: '早 一郎', よみ: 'ハヤ イチロウ',
      月々の金額: 30000, 回数: 12, 支払日: 早い日, 開始月: 開始2 });
    await 作る({ 名前: '遅 二郎', よみ: 'オソ ジロウ',
      月々の金額: 50000, 回数: 12, 支払日: 遅い日, 開始月: 開始2 });

    let dd = await 見る();
    const 今 = 月を引く(dd, 今月);
    check('今月が出ている', !!今, dd.月.map((m) => m.年月));
    check('予定回収額は期日の来たぶんだけ', 今 && 今.予定回収額 === 30000,
      今 && 今.予定回収額);
    check('期日前の額を返す', 今 && 今.期日前額 === 50000, 今 && 今.期日前額);
    check('期日前の件数を返す', 今 && 今.期日前件数 === 1, 今 && 今.期日前件数);
    check('月の合計は両方を足した80,000円', 今 && 今.月の合計 === 80000, 今 && 今.月の合計);
    check('予定＋期日前＝月の合計',
      今 && 今.予定回収額 + 今.期日前額 === 今.月の合計,
      [今.予定回収額, 今.期日前額, 今.月の合計]);
    check('期日の来た回だけが未回収に入る', 今 && 今.未回収額 === 30000,
      今 && 今.未回収額);
    check('全件は期日の来た回だけ', 今 && 今.全件 === 1, 今 && 今.全件);

    console.log('■ 期日の全部過ぎた月には、期日前は付かない');
    const 先 = 月を引く(dd, 前月(1));
    check('先月の期日前は0円', 先 && 先.期日前額 === 0, 先 && 先.期日前額);
    check('先月の期日前は0件', 先 && 先.期日前件数 === 0, 先 && 先.期日前件数);
    check('先月の予定は月まるごと', 先 && 先.予定回収額 === 80000, 先 && 先.予定回収額);
    check('先月は予定＝月の合計', 先 && 先.予定回収額 === 先.月の合計,
      [先 && 先.予定回収額, 先 && 先.月の合計]);

    console.log('■ 今月の分を払っても、予定回収額は変わらない');
    // 充当は古い回から埋める。先月ぶんも一緒に払わないと今月は埋まらない
    await 払う(E.id, `${今月}-${String(早い日).padStart(2, '0')}`, 60000);
    dd = await 見る();
    const 今2 = 月を引く(dd, 今月);
    // 期日の来た1件が入金済みになると、行が空になって月ごと消える。
    // 消えなければ予定回収額は変わらない
    if (今2) {
      check('予定回収額は30,000円のまま', 今2.予定回収額 === 30000, 今2.予定回収額);
      check('月の合計は80,000円のまま', 今2.月の合計 === 80000, 今2.月の合計);
      check('未回収額は0円', 今2.未回収額 === 0, 今2.未回収額);
    } else {
      check('全部回収できた月は消える', true);
    }
  } else {
    check('今日が月初か月末のため、今月ぶんの検査は飛ばす', true, [今日, 末日]);
  }

  console.log('■ 引き上げた顧客は予定回収額に入れない');
  await reset();
  await call('setup', { method: 'POST', body: {} });
  const A2 = await 作る({ 名前: 'ダッシュ 一郎', よみ: 'ダッシュ イチロウ',
    月々の金額: 30000, 回数: 6, 支払日: 20, 開始月: 開始 });
  const B2 = await 作る({ 名前: 'ダッシュ 二郎', よみ: 'ダッシュ ジロウ',
    月々の金額: 50000, 回数: 6, 支払日: 20, 開始月: 開始 });
  await call('customer', { method: 'PATCH', body: {
    id: B2.id, 状態: '回収', 状態日: `${開始}-25` } });
  {
    const dd = await 見る();
    const m5 = 月を引く(dd, 開始);
    check('二郎のぶんが抜ける', m5 && m5.予定回収額 === 30000, m5 && m5.予定回収額);
  }

  await client.end();
  done();
})();
