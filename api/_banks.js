// 銀行ごとの差し込み口。
//
// 銀行によって、つなぎ方も返ってくる形もばらばらになる。
// その違いを全部ここに閉じ込め、外へは同じ形だけを渡す。
// 銀行を足すときに触るのはこのファイルだけ、というのが狙い。
//
// 外へ渡す形（これだけあれば台帳は動く）:
//   { 取引通番, 日付:'YYYY-MM-DD', 金額:整数, 振込人, 付番, 生 }
//
// 合鍵（接続の鍵）はこのファイルにも台帳にも書かない。環境変数から読む。
// 都市銀行・地方銀行は銀行ごとに認証のしくみが違うので、
// 実物の差し込み口は、その銀行の仕様が分かってから足す。

// 入金だけを扱う。出金・振替は台帳に入れない
const 入金だけ = (行) => 行.filter((x) => Number(x.金額) > 0);

// 日付をそろえる。銀行は 20260809 / 2026/08/09 / 2026-08-09 のどれでも返してくる
function 日付にする(v) {
  const s = String(v == null ? '' : v).trim();
  let m = s.match(/^(\d{4})[-/]?(\d{2})[-/]?(\d{2})$/);
  if (m) return `${m[1]}-${m[2]}-${m[3]}`;
  m = s.match(/^(\d{4})[-/](\d{1,2})[-/](\d{1,2})$/);
  if (m) return `${m[1]}-${String(m[2]).padStart(2, '0')}-${String(m[3]).padStart(2, '0')}`;
  return null;
}

// 金額をそろえる。「30,000」「30000円」でも通す
function 金額にする(v) {
  const n = Math.round(Number(String(v == null ? '' : v).replace(/[^0-9-]/g, '')));
  return Number.isFinite(n) ? n : 0;
}

// 取引通番が無い銀行のための鍵。
// 日付・金額・振込人が同じ入金は同じ日に2件あり得るので、同日の連番も混ぜる
function 通番を作る(行, 連番) {
  return `${行.日付}|${行.金額}|${String(行.振込人 || '')}|${連番}`;
}

// ── 動作を試すための銀行 ───────────────────────
// 本物の銀行につながなくても、取得から確認・取り込みまでを通しで試せるようにする。
// 環境変数 BANK_TEST_ROWS に明細をJSONで入れておくと、それを返す。
// 入れていなければ空を返す（何も起きない）。
const テスト銀行 = {
  名前: 'テスト銀行',
  説明: '動作を試すための差し込み口。本物の銀行にはつながりません。',
  async 取ってくる(口座, { 開始日, 終了日 }) {
    let 生 = [];
    try {
      生 = JSON.parse(process.env.BANK_TEST_ROWS || '[]');
    } catch { 生 = []; }
    if (!Array.isArray(生)) 生 = [];
    return 生
      .filter((x) => {
        const d = 日付にする(x.日付);
        return d && (!開始日 || d >= 開始日) && (!終了日 || d <= 終了日);
      })
      .map((x) => ({
        取引通番: x.取引通番 ? String(x.取引通番) : null,
        日付: 日付にする(x.日付),
        金額: 金額にする(x.金額),
        振込人: String(x.振込人 || ''),
        付番: String(x.付番 || ''),
        生: x,
      }));
  },
};

const 差し込み口 = {
  テスト: テスト銀行,
};

// 口座から明細を取ってくる。返す形はどの銀行でも同じ。
// 通番の無い明細には、ここで鍵を作ってから返す（重複を弾くため）。
async function 取ってくる(口座, 期間) {
  const 口 = 差し込み口[口座.kind];
  if (!口) throw new Error(`「${口座.kind}」という差し込み口はありません。`);
  const 行 = await 口.取ってくる(口座, 期間 || {});
  const 使えるもの = 入金だけ(行.filter((x) => x.日付 && x.金額));
  const 数 = {};
  return 使えるもの.map((x) => {
    if (x.取引通番) return x;
    const k = `${x.日付}|${x.金額}|${x.振込人}`;
    数[k] = (数[k] || 0) + 1;
    return { ...x, 取引通番: 通番を作る(x, 数[k]) };
  });
}

const 差し込み口の一覧 = () =>
  Object.entries(差し込み口).map(([kind, x]) => ({ kind, 名前: x.名前, 説明: x.説明 }));

export { 取ってくる, 差し込み口の一覧, 日付にする, 金額にする };
